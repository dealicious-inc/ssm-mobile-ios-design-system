// MARK: - Size
enum TextLinkSizeType {
    case large
    case medium
    case small
    
    var size: TextLinkSize {
        switch self {
        case .large:
            return TextLinkSize(height: 20, font: .b1sb15)
        case .medium:
            return TextLinkSize(height: 20, font: .b2r14)
        case .small:
            return TextLinkSize(height: 18, font: .b3r13)
        }
    }
}


// MARK: - Style
enum TextLinkStyleType {
    // 네이밍은 textColor 를 따름
    case primary01
    case primary04
    case secondary01
    case g100
    case g80
    case g70
    case g60

    var style: TextLinkStyle {
        switch self {
        case .primary01:
            return TextLinkStyle(
                colorProvider: TextLinkColors(
                    normal: TextLinkColor(textColor: .primary01, backgroundColor: .clear),
                    disabled: TextLinkColor(textColor: .g50, backgroundColor: .clear)
                )
            )
            
        case .primary04:
            return TextLinkStyle(
                colorProvider: TextLinkColors(
                    normal: TextLinkColor(textColor: .primary04, backgroundColor: .clear),
                    disabled: TextLinkColor(textColor: .w50, backgroundColor: .clear)
                )
            )
            
        case .secondary01:
            return TextLinkStyle(
                colorProvider: TextLinkColors(
                    normal: TextLinkColor(textColor: .secondary01, backgroundColor: .clear),
                    disabled: TextLinkColor(textColor: .g50, backgroundColor: .clear)
                )
            )
        case .g100:
            return TextLinkStyle(
                colorProvider: TextLinkColors(
                    normal: TextLinkColor(textColor: .g100, backgroundColor: .clear),
                    disabled: TextLinkColor(textColor: .g50, backgroundColor: .clear)
                )
            )
        case .g80:
            return TextLinkStyle(
                colorProvider: TextLinkColors(
                    normal: TextLinkColor(textColor: .g80, backgroundColor: .clear),
                    disabled: TextLinkColor(textColor: .g50, backgroundColor: .clear)
                )
            )
        case .g70:
            return TextLinkStyle(
                colorProvider: TextLinkColors(
                    normal: TextLinkColor(textColor: .g70, backgroundColor: .clear),
                    disabled: TextLinkColor(textColor: .g50, backgroundColor: .clear)
                )
            )
        case .g60:
            return TextLinkStyle(
                colorProvider: TextLinkColors(
                    normal: TextLinkColor(textColor: .g60, backgroundColor: .clear),
                    disabled: TextLinkColor(textColor: .g50, backgroundColor: .clear)
                )
            )
        }
    }
}
